/*
 * data_model.h —— 任务之间传递的数据契约（app 组件私有）
 *
 * 为什么要把"一条采样记录长什么样"单独抽成一个头文件？
 *
 *   引入队列之前，"数据"和"读数据的代码"是绑死的：
 *   telemetry_task 里读出来的 dht11_reading_t 就地格式化、就地打印，
 *   中间没有任何独立的表示形态，也就不需要契约。
 *
 *   一旦经过队列，就出现了**第二个持有者**——队列本身，以及队列
 *   另一头的消费者。"一条记录由哪些字段构成"于是变成两个任务之间的
 *   契约，必须有一个双方都看得到、又不隶属于任何一方的定义。
 *
 *   注意 dht11.h 和本文件的区别：
 *     dht11.h     定义"传感器能给我什么"（驱动边界）
 *     data_model.h 定义"我们决定在系统里传什么"（系统内部契约）
 *   两者不是一回事。将来换成 SHT30（浮点、带小数、I²C），
 *   dht11_reading_t 会整个消失，但 sensor_data_t 只会跟着改字段类型，
 *   不会跟着消失——因为"换传感器"和"换传输协议"是两个独立的变化方向，
 *   中间需要一层稳定的表示。这是"按变化的原因切"的又一次应用。
 *
 * 关于字段的取舍（本阶段 vs 接 MQTT 时）：
 *
 *   device_id / timestamp_ms / seq —— **现在就放**。
 *     它们不依赖任何外设或网络，纯粹是"这条记录的身份信息"。
 *     早放进来可以避免方案 B 时再动一次结构体布局，
 *     而且报文升级成文档 §14 的正式格式时这几个字段直接用。
 *
 *   rssi —— **故意先不放**。
 *     它来自 WiFi 驱动（需要 wifi_mgr 暴露一个 RSSI 查询接口），
 *     而本阶段的目标是"把本地管道单独验证通"，不引入任何新的
 *     网络相关依赖。等接 MQTT、报文格式定型时一起加，那时才有必要。
 */
#pragma once

#include <stdint.h>

/**
 * @brief 一条温湿度采样记录
 *
 * 这是采样任务与消费者任务之间的契约：生产者填、消费者读，
 * 双方都不直接依赖 dht11 驱动的类型。
 */
typedef struct {
    /*
     * 设备标识。
     *
     * 为什么是定长数组而不是 const char *？
     *   因为这条记录要**按值**塞进队列——xQueueSend 做的是内存拷贝。
     *   如果这里放指针，拷贝过去的只是地址，而队列另一端取出来时，
     *   那块内存可能早已失效。定长数组让整条记录自包含，
     *   元素的生存期与队列本身一致，不依赖任何外部对象。
     *   （"结构体里藏指针再塞队列"是队列传参最经典的坑。）
     *
     * 32 字节是文档 §7.1 定的，够放 "esp32s3_001" 这类名字。
     */
    char     device_id[32];

    /*
     * 时间戳，毫秒。
     *
     * 现在填的是**单调时钟**（esp_timer_get_time()/1000，开机以来的
     * 毫秒数），不是 Unix 时间——因为本阶段还没有 NTP。
     * 接上时间同步后换成真正的 Unix 毫秒时间戳，字段本身不用改。
     *
     * 为什么现在就要填：消费端需要一个"这条记录什么时候采的"依据，
     * 哪怕只是相对时间。等真需要绝对时间再补，历史数据里就少了一段
     * 可对齐的锚点。
     */
    int64_t  timestamp_ms;

    /*
     * 温度（摄氏度整数）与相对湿度（百分比整数）。
     *
     * 为什么是 int 而不是文档 §14 写的 float？
     *   因为 DHT11 的输出本来就没有小数位——手册规定小数字节恒为 0。
     *   用 float 只是把一个整数装进浮点类型，白白引入浮点格式化开销
     *   （MCU 上 snprintf 处理 %f 会链进一大坨代码）。
     *   将来换 SHT30（0.01℃ 分辨率）时再改成定点或浮点——那正是
     *   "换传感器"带来的变化，本就该由这一层吸收。
     */
    int      temperature;
    int      humidity;

    /*
     * 消息序号，从 1 开始单调递增。
     *
     * 作用见文档 §15：接收端看到 seq 跳号就知道中间丢过数据。
     * 注意这是**生产者侧**的计数器——队列满被丢掉的那条，
     * seq 照样已经加过了。所以跳号同时包含"本地队列溢出"和
     * "网络丢包"两种可能，排查时两者都要看。
     */
    uint32_t seq;
} sensor_data_t;
